import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL_MARKDOWN_FILES = ["SKILL.md", "Skill.md"];
const FRONTMATTER_PATTERN = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/;
const scriptDir = dirname(fileURLToPath(import.meta.url));
const installerRoot = resolve(scriptDir, "..");
const repoRoot = resolve(installerRoot, "..");
const skillsRoot = join(repoRoot, "skills");
const outputPath = join(installerRoot, "src", "core", "source-skill-index.generated.ts");

function stripWrappingQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }

  return value;
}

function parseFrontmatterDescription(markdown) {
  const frontmatterMatch = markdown.match(FRONTMATTER_PATTERN);
  if (!frontmatterMatch) {
    return null;
  }

  const descriptionLine = frontmatterMatch[1]
    .split(/\r?\n/)
    .find((line) => line.trimStart().startsWith("description:"));

  if (!descriptionLine) {
    return null;
  }

  const rawDescription = descriptionLine.slice(descriptionLine.indexOf(":") + 1).trim();
  if (rawDescription.length === 0) {
    return null;
  }

  return stripWrappingQuotes(rawDescription);
}

function normalizeSearchText(markdown) {
  return markdown
    .replace(FRONTMATTER_PATTERN, "")
    .replace(/```/g, " ")
    .replace(/`/g, " ")
    .replace(/\[(.*?)\]\((.*?)\)/g, "$1 $2")
    .replace(/[>#*_~-]+/g, " ")
    .replace(/\r?\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

async function pathIsDirectory(path) {
  try {
    return (await stat(path)).isDirectory();
  } catch {
    return false;
  }
}

async function pathIsFile(path) {
  try {
    return (await stat(path)).isFile();
  } catch {
    return false;
  }
}

async function resolveSkillMarkdownPath(skillDir) {
  for (const fileName of SKILL_MARKDOWN_FILES) {
    const candidatePath = join(skillDir, fileName);
    if (await pathIsFile(candidatePath)) {
      return candidatePath;
    }
  }

  return null;
}

async function discoverBinCommands(skillDir) {
  const binDir = join(skillDir, "bin");
  if (!(await pathIsDirectory(binDir))) {
    return [];
  }

  const entries = await readdir(binDir);
  const commands = [];

  for (const entry of entries) {
    const candidatePath = join(binDir, entry);
    if (await pathIsFile(candidatePath)) {
      commands.push(entry);
    }
  }

  return commands.sort((left, right) => left.localeCompare(right));
}

async function loadExportedCommands(skillDir) {
  const manifestPath = join(skillDir, "agent-skills.json");
  const commandsFromBin = await discoverBinCommands(skillDir);

  try {
    const rawManifest = JSON.parse(await readFile(manifestPath, "utf-8"));
    if (rawManifest.exportedCommands === undefined) {
      return commandsFromBin;
    }

    if (
      !Array.isArray(rawManifest.exportedCommands) ||
      !rawManifest.exportedCommands.every((command) => typeof command === "string")
    ) {
      throw new Error(`Invalid exportedCommands in ${manifestPath}`);
    }

    return [...new Set(rawManifest.exportedCommands)].sort((left, right) => left.localeCompare(right));
  } catch (error) {
    if (error && typeof error === "object" && error.code === "ENOENT") {
      return commandsFromBin;
    }

    throw error;
  }
}

function toPosixRelativePath(path) {
  return relative(repoRoot, path).split("\\").join("/");
}

function serializeForTypeScript(value) {
  return JSON.stringify(value, null, 2)
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

async function buildSourceSkillIndex() {
  const entries = await readdir(skillsRoot);
  const sourceSkillIndex = [];

  for (const entry of entries.sort((left, right) => left.localeCompare(right))) {
    const skillDir = join(skillsRoot, entry);
    if (!(await pathIsDirectory(skillDir))) {
      continue;
    }

    const markdownPath = await resolveSkillMarkdownPath(skillDir);
    if (!markdownPath) {
      continue;
    }

    const markdown = await readFile(markdownPath, "utf-8");
    sourceSkillIndex.push({
      name: entry,
      description: parseFrontmatterDescription(markdown),
      exportedCommands: await loadExportedCommands(skillDir),
      path: toPosixRelativePath(skillDir),
      source: "source",
      searchText: normalizeSearchText(markdown),
    });
  }

  return sourceSkillIndex;
}

async function main() {
  const sourceSkillIndex = await buildSourceSkillIndex();
  const fileContents = `import type { SourceSkillIndexEntry } from "./types.js";

/**
 * Generated by scripts/generate-source-skill-index.mjs.
 * Do not edit by hand.
 */
export const SOURCE_SKILL_INDEX = ${serializeForTypeScript(sourceSkillIndex)} satisfies ReadonlyArray<SourceSkillIndexEntry>;
`;

  await writeFile(outputPath, fileContents, "utf-8");
  process.stdout.write(`Wrote ${sourceSkillIndex.length} source skill index entries to ${outputPath}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exit(1);
});
